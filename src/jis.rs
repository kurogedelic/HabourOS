//! Unicode → JIS X 0208 変換ユーティリティ。
//!
//! M+ の日本語 BDF は ENCODING に JIS X 0208 コード（区点の16進表現、
//! 例: 'あ' = 0x2422）を使っている。Unicode から引くために変換が必要。
//!
//! 変換テーブルは tools/gen_jis_table.py が生成する jis_table.rs を使用。

mod jis_table {
    include!("jis_table.rs");
}

/// Unicode (U+XXXX) → JIS X 0208 コード（0x2121..0x7E7E）。
/// 変換不能（ASCII 半角・JIS外字など）は None。
pub fn unicode_to_jis(ch: char) -> Option<u32> {
    // 半角カナ U+FF61..FF9F は全角カナへ正規化してから変換
    let ch = normalize_half_kana(ch);
    let u = ch as u32;

    // ASCII は JIS 外（Latin-1 フォント側で処理）
    if u < 0x80 {
        return None;
    }

    // ソート済みテーブルを二分探索
    let table = jis_table::UNICODE_TO_JIS;
    let idx = table.binary_search_by(|(code, _)| code.cmp(&u)).ok()?;
    Some(table[idx].1)
}

/// 半角カナ U+FF61..FF9F を全角カナへ正規化。
fn normalize_half_kana(ch: char) -> char {
    let half_to_full: &[(char, char)] = &[
        ('｡', '。'),
        ('｢', '「'),
        ('｣', '」'),
        ('､', '、'),
        ('ｦ', 'ヲ'),
        ('ｧ', 'ァ'),
        ('ｨ', 'ィ'),
        ('ｩ', 'ゥ'),
        ('ｪ', 'ェ'),
        ('ｫ', 'ォ'),
        ('ｬ', 'ャ'),
        ('ｭ', 'ュ'),
        ('ｮ', 'ョ'),
        ('ｯ', 'ッ'),
        ('ｰ', 'ー'),
        ('ｱ', 'ア'),
        ('ｲ', 'イ'),
        ('ｳ', 'ウ'),
        ('ｴ', 'エ'),
        ('ｵ', 'オ'),
        ('ｶ', 'カ'),
        ('ｷ', 'キ'),
        ('ｸ', 'ク'),
        ('ｹ', 'ケ'),
        ('ｺ', 'コ'),
        ('ｻ', 'サ'),
        ('ｼ', 'シ'),
        ('ｽ', 'ス'),
        ('ｾ', 'セ'),
        ('ｿ', 'ソ'),
        ('ﾀ', 'タ'),
        ('ﾁ', 'チ'),
        ('ﾂ', 'ツ'),
        ('ﾃ', 'テ'),
        ('ﾄ', 'ト'),
        ('ﾅ', 'ナ'),
        ('ﾆ', 'ニ'),
        ('ﾇ', 'ヌ'),
        ('ﾈ', 'ネ'),
        ('ﾉ', 'ノ'),
        ('ﾊ', 'ハ'),
        ('ﾋ', 'ヒ'),
        ('ﾌ', 'フ'),
        ('ﾍ', 'ヘ'),
        ('ﾎ', 'ホ'),
        ('ﾏ', 'マ'),
        ('ﾐ', 'ミ'),
        ('ﾑ', 'ム'),
        ('ﾒ', 'メ'),
        ('ﾓ', 'モ'),
        ('ﾔ', 'ヤ'),
        ('ﾕ', 'ユ'),
        ('ﾖ', 'ヨ'),
        ('ﾗ', 'ラ'),
        ('ﾘ', 'リ'),
        ('ﾙ', 'ル'),
        ('ﾚ', 'レ'),
        ('ﾛ', 'ロ'),
        ('ﾜ', 'ワ'),
        ('ﾝ', 'ン'),
    ];
    for (h, f) in half_to_full {
        if ch == *h {
            return *f;
        }
    }
    ch
}
